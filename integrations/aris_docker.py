"""Docker execution helpers for ARIS benchmark integration."""

from __future__ import annotations

import json
from pathlib import Path

from agent_container import scrub_base_url, workdir_for_run


def container_home_for_run(run_root: Path) -> Path:
    return run_root / ".container-home"


def containerize_aris_base_url(base_url: str, host_env: dict[str, str]) -> str:
    """Rewrite localhost proxy URLs so ARIS inside Docker can reach the host."""
    from agent_container import HOST_GATEWAY_ALIAS, _is_metering_proxy_url

    url = (base_url or "").strip().rstrip("/")
    if not url:
        return scrub_base_url(host_env).rstrip("/")
    if _is_metering_proxy_url(url) and ("127.0.0.1" in url or "localhost" in url):
        return url.replace("127.0.0.1", HOST_GATEWAY_ALIAS).replace("localhost", HOST_GATEWAY_ALIAS)
    if "127.0.0.1" in url or "localhost" in url:
        return scrub_base_url(host_env).rstrip("/")
    return url


def write_aris_runtime_config(run_root: Path, config: dict[str, object]) -> Path:
    """Write ~/.config/aris/config.json under the per-run container HOME."""
    home = container_home_for_run(run_root)
    home.mkdir(parents=True, exist_ok=True)
    config_dir = home / ".config" / "aris"
    config_dir.mkdir(parents=True, exist_ok=True)
    config_path = config_dir / "config.json"
    config_path.write_text(json.dumps(config, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return config_path


def aris_process_env(config: dict[str, object]) -> dict[str, str]:
    """Environment variables ARIS reads before opening config files."""
    executor_key = str(config.get("executor_api_key") or "")
    executor_base = str(config.get("executor_base_url") or "").rstrip("/")
    executor_model = str(config.get("executor_model") or "")
    reviewer_key = str(config.get("reviewer_api_key") or executor_key)
    reviewer_base = str(config.get("reviewer_base_url") or executor_base).rstrip("/")
    env: dict[str, str] = {
        "EXECUTOR_PROVIDER": str(config.get("executor_provider") or "openai"),
        "EXECUTOR_API_KEY": executor_key,
        "EXECUTOR_BASE_URL": executor_base,
        "OPENAI_API_KEY": executor_key,
        "OPENAI_BASE_URL": executor_base,
        "ANTHROPIC_API_KEY": executor_key,
        "ANTHROPIC_BASE_URL": executor_base,
        "ARIS_LANGUAGE": str(config.get("language") or "en"),
    }
    if executor_model:
        env["EXECUTOR_MODEL"] = executor_model
    if config.get("reviewer_provider"):
        env["ARIS_REVIEWER_PROVIDER"] = str(config["reviewer_provider"])
    if reviewer_key:
        env["ARIS_REVIEWER_AUTH_TOKEN"] = reviewer_key
    if reviewer_base:
        env["ARIS_REVIEWER_BASE_URL"] = reviewer_base
    if config.get("reviewer_model"):
        env["ARIS_REVIEWER_MODEL"] = str(config["reviewer_model"])
    return env


def workplace_container_path(task_env: dict[str, str]) -> str:
    return task_env.get("WORKPLACE_CONTAINER_PATH", "/workplace").strip() or "/workplace"


def docker_workdir_for_run(workplace_path: str, run_root: Path, workspace_root: Path) -> str:
    del workplace_path, workspace_root
    return workdir_for_run(run_root)


def write_benchmark_env(
    run_root: Path,
    *,
    container_id: str,
    docker_workdir: str,
    host_run_root: Path,
) -> Path:
    env_dir = run_root / ".aris-benchmark"
    env_dir.mkdir(parents=True, exist_ok=True)

    env_json = env_dir / "env.json"
    env_json.write_text(
        json.dumps(
            {
                "container_id": container_id,
                "docker_workdir": docker_workdir,
                "host_run_root": str(host_run_root.resolve()),
                "execution_mode": "in_container",
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )

    env_file = env_dir / "env.sh"
    env_file.write_text(
        "\n".join(
            [
                "# Generated by run_aris_task.py — do not edit manually.",
                f'export ARIS_DOCKER_CONTAINER_ID="{container_id}"',
                f'export ARIS_DOCKER_WORKDIR="{docker_workdir}"',
                f'export ARIS_HOST_RUN_ROOT="{host_run_root.resolve()}"',
                'export BENCHMARK_AGENT_NATIVE="1"',
                "",
            ]
        ),
        encoding="utf-8",
    )
    return env_file


def write_aris_settings(run_root: Path) -> Path:
    """ARIS runs inside the task container; keep sandbox disabled for shell/tool access."""
    claude_dir = run_root / ".claude"
    claude_dir.mkdir(parents=True, exist_ok=True)
    settings_path = claude_dir / "settings.json"
    settings = {
        "permissionMode": "danger-full-access",
        "sandbox": {
            "enabled": False,
            "strictMode": False,
        },
    }
    if settings_path.is_file():
        try:
            existing = json.loads(settings_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            existing = {}
        if isinstance(existing, dict):
            existing.setdefault("sandbox", {})
            if isinstance(existing["sandbox"], dict):
                existing["sandbox"]["enabled"] = False
                existing["sandbox"]["strictMode"] = False
            existing["permissionMode"] = "danger-full-access"
            settings = existing
    settings_path.write_text(json.dumps(settings, indent=2) + "\n", encoding="utf-8")
    return settings_path
