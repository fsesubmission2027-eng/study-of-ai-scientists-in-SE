# Minimal shared libs required by Playwright Chromium inside ai-scientist-base.
# (base image is Ubuntu 22.04 without browser GUI deps.)
_PLAYWRIGHT_APT_PACKAGES = (
    "libatk-bridge2.0-0",
    "libatk1.0-0",
    "libatspi2.0-0",
    "libgbm1",
    "libxkbcommon0",
    "libnss3",
    "libnspr4",
    "libdrm2",
    "libxcomposite1",
    "libxdamage1",
    "libxfixes3",
    "libxrandr2",
    "libasound2",
    "libcups2",
    "libcairo2",
    "libpango-1.0-0",
    "libx11-xcb1",
    "libxcb-dri3-0",
    "fonts-liberation",
)


def workplace_container_path(task_env: dict[str, str]) -> str:
    """Legacy helper; aligned-path runs use the host run root directly."""
    return task_env.get("WORKPLACE_CONTAINER_PATH", "/workplace").strip() or "/workplace"


def docker_workdir_for_run(workplace_path: str, run_root: Path, workspace_root: Path) -> str:
    del workplace_path, workspace_root
    return workdir_for_run(run_root)


def ensure_playwright_system_deps(container_id: str) -> tuple[bool, str]:
    """Install Chromium shared libraries into the running TaskSandbox (as root)."""
    pkgs = " ".join(_PLAYWRIGHT_APT_PACKAGES)
    probe = subprocess.run(
        [
            "docker",
            "exec",
            container_id,
            "bash",
            "-lc",
            "ldconfig -p | grep -q 'libgbm.so.1' && ldconfig -p | grep -q 'libatk-bridge-2.0.so.0'",
        ],
        check=False,
        capture_output=True,
        text=True,
    )
    if probe.returncode == 0:
        return True, "playwright system deps already present"

    cmd = (
        "set -euo pipefail; "
        "export DEBIAN_FRONTEND=noninteractive; "
        "apt-get update -qq; "
        f"apt-get install -y --no-install-recommends {pkgs}; "
        "ldconfig; "
        "echo '[airesearcher] playwright system deps installed'"
    )
    proc = subprocess.run(
        ["docker", "exec", "-u", "0", container_id, "bash", "-lc", cmd],
        check=False,
        capture_output=True,
        text=True,
        timeout=1800,
        stdin=subprocess.DEVNULL,
    )
    detail = ((proc.stdout or "") + "\n" + (proc.stderr or "")).strip()
    if proc.returncode != 0:
        tail = detail.splitlines()[-1] if detail else f"exit {proc.returncode}"
        return False, f"playwright apt install failed: {tail}"
    return True, "playwright system deps installed"


def write_benchmark_env(
    run_root: Path,
    *,
    container_id: str,
    docker_workdir: str,
    host_run_root: Path,
    instance_path: Path | None = None,
) -> Path:
    env_dir = run_root / ".airesearcher-benchmark"
    env_dir.mkdir(parents=True, exist_ok=True)

    payload = {
        "container_id": container_id,
        "docker_workdir": docker_workdir,
        "host_run_root": str(host_run_root.resolve()),
        "execution_mode": "in_container",
    }
    if instance_path is not None:
        payload["instance_path"] = str(instance_path.resolve())

    env_json = env_dir / "env.json"
    env_json.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")

    lines = [
        "# Generated by run_airesearcher_task.py — do not edit manually.",
        f'export AIRESEARCHER_DOCKER_CONTAINER_ID="{container_id}"',
        f'export AIRESEARCHER_DOCKER_WORKDIR="{docker_workdir}"',
        f'export AIRESEARCHER_HOST_RUN_ROOT="{host_run_root.resolve()}"',
        f'export BENCHMARK_RUN_ROOT="{host_run_root.resolve()}"',
        'export BENCHMARK_AGENT_NATIVE="1"',
    ]
    if instance_path is not None:
        lines.append(f'export AIRESEARCHER_INSTANCE_PATH="{instance_path.resolve()}"')
    lines.append("")

    env_file = env_dir / "env.sh"
    env_file.write_text("\n".join(lines), encoding="utf-8")
    return env_file
