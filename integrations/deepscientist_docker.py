def benchmark_env_dir(run_root: Path) -> Path:
    return run_root / ".ds-benchmark"


def build_benchmark_execution_env(
    run_root: Path,
    *,
    container_id: str | None = None,
    docker_workdir: str | None = None,
) -> dict[str, str]:
    run_root = run_root.resolve()
    workdir = docker_workdir or str(run_root)
    env = {
        BENCHMARK_RUN_ROOT_ENV: str(run_root),
        "BENCHMARK_AGENT_NATIVE": "1",
    }
    if container_id:
        env.update(
            {
                "DS_DOCKER_CONTAINER_ID": container_id,
                "DEEPSCIENTIST_DOCKER_CONTAINER_ID": container_id,
                "DS_DOCKER_WORKDIR": workdir,
                "DEEPSCIENTIST_DOCKER_WORKSPACE_ROOT": workdir,
                "DS_HOST_WORKSPACE": str(run_root),
                "DEEPSCIENTIST_HOST_WORKSPACE_ROOT": str(run_root),
            }
        )
    return env


def write_benchmark_env(
    run_root: Path,
    *,
    container_id: str,
    docker_workdir: str,
    host_run_root: Path | None = None,
) -> Path:
    host_root = (host_run_root or run_root).resolve()
    env_dir = benchmark_env_dir(run_root)
    env_dir.mkdir(parents=True, exist_ok=True)
    env_file = env_dir / "env.sh"
    values = build_benchmark_execution_env(
        host_root,
        container_id=container_id,
        docker_workdir=docker_workdir,
    )
    lines = ["# Generated by run_deepscientist_task.py — do not edit manually."]
    for key in sorted(values):
        lines.append(f'export {key}="{values[key]}"')
    lines.append("")
    env_file.write_text("\n".join(lines), encoding="utf-8")
    return env_file


def write_opencode_scrub_config(
    ds_home: Path,
    *,
    scrub_base_url: str,
    source_config: Path | None = None,
) -> Path:
    """Per-run OpenCode config with literature_scrub as the Modelverse base URL."""
    config_dir = ds_home / "config" / "opencode"
    config_dir.mkdir(parents=True, exist_ok=True)
    target = config_dir / "opencode.json"
    source = source_config or Path.home() / ".config/opencode/opencode.json"
    if source.is_file():
        payload = json.loads(source.read_text(encoding="utf-8"))
    else:
        payload = {
            "$schema": "https://opencode.ai/config.json",
            "provider": {},
        }
    provider = payload.setdefault("provider", {})
    modelverse = provider.setdefault("modelverse", {})
    options = modelverse.setdefault("options", {})
    options["baseURL"] = scrub_base_url.rstrip("/")
    options.setdefault("apiKey", "{env:OPENAI_API_KEY}")
    target.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return config_dir


def install_bash_exec_jail(run_root: Path) -> Path:
    """Install a PATH-first bash shim so DeepScientist bash_exec runs inside the run sandbox."""
    bin_dir = benchmark_env_dir(run_root) / "bin"
    bin_dir.mkdir(parents=True, exist_ok=True)
    jail_path = bin_dir / "bash"
    real_bash = shutil.which("bash") or "/usr/bin/bash"
    jail_path.write_text(
        "\n".join(
            [
                "#!/usr/bin/bash",
                "set -euo pipefail",
                f'REAL_BASH="${{BENCHMARK_REAL_BASH:-{real_bash}}}"',
                f'RUN_ROOT="${{{BENCHMARK_RUN_ROOT_ENV}:-}}"',
                'CONTAINER="${DS_DOCKER_CONTAINER_ID:-${DEEPSCIENTIST_DOCKER_CONTAINER_ID:-}}"',
                'WORKDIR="${DS_DOCKER_WORKDIR:-${DEEPSCIENTIST_DOCKER_WORKSPACE_ROOT:-}}"',
                "",
                'if [[ -n "${CONTAINER}" ]] && command -v docker >/dev/null 2>&1; then',
                '  if [[ -z "${WORKDIR}" && -n "${RUN_ROOT}" ]]; then',
                '    WORKDIR="${RUN_ROOT}"',
                "  fi",
                '  exec docker exec -i -w "${WORKDIR}" "${CONTAINER}" "${REAL_BASH}" "$@"',
                "fi",
                "",
                'if [[ -n "${RUN_ROOT}" ]]; then',
                '  echo "benchmark bash_exec jail: refusing host bash outside isolated run root (${RUN_ROOT}). '
                'Use --execution-mode container." >&2',
                "  exit 1",
                "fi",
                "",
                'exec "${REAL_BASH}" "$@"',
                "",
            ]
        ),
        encoding="utf-8",
    )
    jail_path.chmod(0o755)
    return bin_dir


def _symlink_into_quest(link_path: Path, target: Path) -> None:
    target.parent.mkdir(parents=True, exist_ok=True)
    if link_path.is_symlink():
        try:
            if link_path.resolve() == target.resolve():
                return
        except OSError:
            pass
        link_path.unlink(missing_ok=True)
    elif link_path.exists():
        if link_path.is_dir() and not link_path.is_symlink():
            return
        link_path.unlink(missing_ok=True)
    os.symlink(target, link_path, target_is_directory=target.is_dir())


def link_quest_workspace_dirs(quest_root: Path, run_root: Path) -> None:
    """Symlink task deliverable paths into the quest cwd so DS writes land under the run root."""
    run_root.mkdir(parents=True, exist_ok=True)
    for name in ("project", "results", "dataset_candidate", "paper", "tmp"):
        _symlink_into_quest(quest_root / name, run_root / name)

    for name in ("idea.md", "README.md", "REPORT.md"):
        target = run_root / name
        if not target.exists():
            target.write_text(f"# {name.removesuffix('.md')}\n", encoding="utf-8")
        _symlink_into_quest(quest_root / name, target)


def configure_quest_run_workspace(quest_dir: Path, run_root: Path) -> None:
    """Pin DeepScientist worktree/active workspace to the isolated benchmark run root."""
    state_path = quest_dir / ".ds" / "research_state.json"
    state_path.parent.mkdir(parents=True, exist_ok=True)
    run_root = run_root.resolve()
    payload: dict[str, object] = {}
    if state_path.is_file():
        try:
            payload = json.loads(state_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            payload = {}
    payload["research_head_worktree_root"] = str(run_root)
    payload["current_workspace_root"] = str(run_root)
    state_path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def seed_task_workspace_host(run_root: Path, task_dir: Path) -> None:
    """Prepare host workspace under the per-run directory (legacy host mode)."""
    from path_alignment import load_task_env

    seeds = task_dir / "seeds"
    req = seeds / "requirements.txt"
    for sub in ("dataset_candidate", "project", "results", "paper", "tmp"):
        (run_root / sub).mkdir(parents=True, exist_ok=True)

    if seeds.is_dir():
        stage_seeds_for_agent(
            seeds,
            run_root / "dataset_candidate",
            task_env=load_task_env(task_dir),
        )

    if req.is_file():
        subprocess.run(
            [sys.executable, "-m", "pip", "install", "-r", str(req)],
            check=False,
        )


def build_runtime_constraints(
    *,
    host_workspace: Path,
    execution_mode: str = EXECUTION_MODE_CONTAINER,
    docker_workdir: str | None = None,
) -> str:
    workdir = docker_workdir or str(host_workspace.resolve())
    lines = [BENCHMARK_RUN_ISOLATION_NOTE, build_runtime_workdir_note(workdir=workdir).strip()]
    if execution_mode in {EXECUTION_MODE_DOCKER, EXECUTION_MODE_CONTAINER}:
        lines.append(
            "- DeepScientist daemon, opencode, and bash_exec run inside the per-run Docker sandbox; "
            "only this run directory is mounted."
        )
        lines.append(
            "- LLM calls use the configured OpenAI-compatible endpoint directly "
            "(literature year/target-paper scrubbing is disabled)."
        )
    else:
        lines.append(
            "- Execution mode: host (quest cwd symlinks into the run root). "
            "Use `--execution-mode container` for filesystem-enforced bash_exec isolation."
        )
    return "\n".join(line for line in lines if line).strip()


